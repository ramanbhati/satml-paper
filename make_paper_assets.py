# COUNT DISTINCT OBSERVATIONS, NOT ROWS. Summing row counts
# gave 24,400, but the sweeps overlap: fix_* and omega_* both measure mode n at
# omega in {1,4} on the same queries, and with --use_cache the second run reuses
# the first run's responses, so those rows are the SAME measurement written
# twice. 1,261 rows are exact re-measurements. The honest figure is 23,139.
#
# The rule below is deliberately conservative: two rows collapse only if they
# agree on the corpus and on EVERY column except `run` (the run id, which
# differs by construction). Any row that differs in any measured value is
# counted separately, so this can only ever under-report duplication.
def _corpus(fn):
    for _d in ('open_nq', 'hotpotqa', 'realtimeqa'):
        if _d in fn:
            return _d
    return fn          # files with no corpus token never merge across files


