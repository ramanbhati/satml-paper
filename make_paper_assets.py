#!/usr/bin/env python
"""
Generate EVERY table and figure in the paper from the result CSVs.

    python3 make_paper_assets.py [--out ../../../paper-satml2027/generated]

WHY THIS EXISTS. Numbers that are retyped into LaTeX drift from the data, and
nothing catches it. An earlier draft of Section 3 claimed "18/18 configurations"
where the CSV supports 15 of 18; that survived only because a human typed it.
Every figure and table the paper prints is emitted here, from the CSV, with the
source file and filter recorded in a comment at the top of each generated file.
Re-run this and rebuild rather than editing anything in generated/.

Outputs (all LaTeX, all self-contained, \\input-ed by the section files):
  tab_surface.tex    parameter surface either side of the vacuity boundary
  tab_omega.tex      attacker keyword survival by model x omega
  tab_vanilla.tex    benign drop vs vanilla RAG, and undefended ASR
  tab_benefit.tex    defense benefit vs the model's own undefended vulnerability
  tab_fix.tex        the floor2 / k mitigation
  fig_ladder.tex     survival vs omega, one line per model  (pgfplots)
  fig_benefit.tex    undefended ASR vs defense benefit, with the inversion
  (fig_tradeoff.tex is deliberately NOT generated; see its section below)
"""
import argparse
import collections
import csv
import math
import os

ap = argparse.ArgumentParser()
# The default writes straight into the paper's tree, which is one level above a
# released copy of this repository and therefore absent for anyone who only has
# the code. Rather than creating '../../../paper-satml2027/generated' out of
# nothing -- which would silently scatter .tex files outside the checkout --
# fall back to a local directory and say so. Pass --out to override either way.
ap.add_argument('--out', default=None,
                help='where to write the .tex assets '
                     '(default: the paper tree if present, else ./generated)')
ap.add_argument('--results', default='results')
A = ap.parse_args()
_PAPER = '../../../paper-satml2027/generated'
if A.out is not None:
    OUT = A.out
elif os.path.isdir(os.path.dirname(_PAPER)):
    OUT = _PAPER
else:
    OUT = 'generated'
    print(f'note: the paper tree is not present, so assets go to ./{OUT}/ .')
    print( '      This is expected for a standalone copy of the code; the '
           'assets are identical either way.')
R = A.results
os.makedirs(OUT, exist_ok=True)

OMEGA = os.path.join(R, 'omega_realtimeqa_k10_all.csv')
VAN = os.path.join(R, 'vanilla_realtimeqa_k10.csv')
SWEEP = os.path.join(R, 'sweep.csv')
FIX = os.path.join(R, 'fix_realtimeqa_k10_all.csv')

# Display names and the order models appear in every table, so the paper is
# internally consistent. Ordered by family then capability.
NAMES = [
    ('mistral7b-bedrock', 'Mistral-7B'),
    ('llama8b-bedrock', 'Llama-3.1-8B'),
    ('llama70b-bedrock', 'Llama-3.3-70B'),
    ('nova-micro-bedrock', 'Nova Micro'),
    ('nova-lite-bedrock', 'Nova Lite'),
    ('nova-pro-bedrock', 'Nova Pro'),
]
DISP = dict(NAMES)
ORDER = [m for m, _ in NAMES]
OMEGAS = [1, 2, 3, 4, 5]


def rows(path):
    if not os.path.exists(path):
        print(f'  !! missing {path} -- skipping the assets that need it')
        return []
    with open(path) as fh:
        return list(csv.DictReader(fh))


def pct(xs):
    return 100.0 * sum(xs) / len(xs) if xs else float('nan')


def mcnemar_exact(b, c):
    n = b + c
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(min(b, c) + 1)) / 2 ** n)


def fmt_p(p):
    return 'p < 0.001' if p < 0.001 else f'p = {p:.3f}'


def write(name, body, source, note=''):
    head = (f'% GENERATED by make_paper_assets.py -- DO NOT EDIT BY HAND.\n'
            f'% source: {source}\n')
    if note:
        head += ''.join(f'% {l}\n' for l in note.strip().splitlines())
    p = os.path.join(OUT, name)
    with open(p, 'w') as fh:
        fh.write(head + body)
    print(f'  wrote {p}')


# =====================================================================
om = rows(OMEGA)
van = rows(VAN)

surv = collections.defaultdict(list)   # (model, omega) -> [0/1]
vac = collections.defaultdict(list)
clean = collections.defaultdict(list)
dasr = collections.defaultdict(list)
for r in om:
    m, w = r['model'], int(r['group_size'])
    if r['k_prime'] == '1':
        surv[(m, w)].append(int(r['attacker_kw_survived']))
        vac[(m, w)].append(1 if float(r['mu']) <= 1.0 else 0)
        a = str(r.get('defended_asr', '')).strip()
        if a != '':
            dasr[(m, w)].append(int(a))
    elif r['k_prime'] == '0':
        c = str(r.get('defended_correct', '')).strip()
        if c != '':
            clean[(m, w)].append(int(c))

vacc = collections.defaultdict(list)   # model -> [0/1] vanilla clean correct
vasr = collections.defaultdict(list)   # model -> [0/1] vanilla ASR
for r in van:
    if r['attack'] == 'none':
        vacc[r['model']].append(int(r['undefended_correct']))
    else:
        a = str(r.get('undefended_asr', '')).strip()
        if a != '':
            vasr[r['model']].append(int(a))

present = [m for m in ORDER if surv.get((m, 1))]

# ---------------------------------------------------------------- tab_omega
if present:
    b = ['\\begin{table}[t]', '  \\centering',
         '  \\caption{Attacker keyword survival with a single poisoned passage '
         '($k\'=1$). At $\\omega\\ge4$ the filter is vacuous on every query for '
         'every model (Theorem~\\ref{thm:unconditional}); what remains is the '
         'model\'s own resistance.}',
         '  \\label{tab:omega}', '  \\begin{tabular}{l' + 'r' * len(OMEGAS) + '}',
         '    \\toprule',
         '    model & ' + ' & '.join(f'$\\omega{{=}}{w}$' for w in OMEGAS) + ' \\\\',
         '    \\midrule']
    for m in present:
        cells = []
        for w in OMEGAS:
            v = pct(surv[(m, w)])
            s = f'{v:.0f}\\%'
            if w >= 4:
                s = f'\\textbf{{{s}}}'
            cells.append(s)
        b.append(f'    {DISP[m]} & ' + ' & '.join(cells) + ' \\\\')
    b += ['    \\bottomrule', '  \\end{tabular}', '\\end{table}']
    write('tab_omega.tex', '\n'.join(b) + '\n', OMEGA,
          'filter: k_prime=1, metric attacker_kw_survived, 100 queries per cell')

# ---------------------------------------------------------------- tab_vanilla
if present and vacc:
    b = ['\\begin{table*}[t]', '  \\centering',
         '  \\caption{Benign accuracy relative to vanilla RAG (percentage points; '
         'negative means the defense costs accuracy), and the undefended attack '
         'success rate. The final column is the control that establishes the '
         'attack works at all.}',
         '  \\label{tab:vanilla}',
         '  \\begin{tabular}{lr' + 'r' * len(OMEGAS) + 'r}', '    \\toprule',
         '    & vanilla & \\multicolumn{%d}{c}{benign drop vs.\\ vanilla} & undef. \\\\'
         % len(OMEGAS),
         '    model & acc. & ' + ' & '.join(f'$\\omega{{=}}{w}$' for w in OMEGAS)
         + ' & ASR \\\\', '    \\midrule']
    for m in present:
        if not vacc.get(m):
            continue
        va = pct(vacc[m])
        cells = [f'{pct(clean[(m, w)]) - va:+.0f}' if clean.get((m, w)) else '--'
                 for w in OMEGAS]
        asr = f'{pct(vasr[m]):.0f}\\%' if vasr.get(m) else '--'
        b.append(f'    {DISP[m]} & {va:.0f}\\% & ' + ' & '.join(cells)
                 + f' & {asr} \\\\')
    b += ['    \\bottomrule', '  \\end{tabular}', '\\end{table*}']
    write('tab_vanilla.tex', '\n'.join(b) + '\n', f'{VAN} joined to {OMEGA} on (model,q_idx)',
          'benign drop: k_prime=0 defended_correct minus vanilla attack=none\n'
          'undefended ASR: vanilla attack=KeywordInjection, undefended_asr')

# ---------------------------------------------------------------- tab_benefit
# Paired per query: undefended ASR (vanilla) against defended ASR at omega=1.
# The captions of tab_benefit and fig_benefit quote the test for any model whose
# point estimate goes the wrong way, so that the caption says what the body says
# ("no measurable benefit") instead of calling a non-significant rise "harm".
_van_q = {(r['model'], r['q_idx']): int(r['undefended_asr']) for r in van
          if r['attack'] != 'none' and str(r.get('undefended_asr', '')).strip() != ''}
_def_q = {(r['model'], r['q_idx']): int(r['defended_asr']) for r in om
          if r['k_prime'] == '1' and r['group_size'] == '1'
          and str(r.get('defended_asr', '')).strip() != ''}
_worse = []
for _m in present:
    if not (vasr.get(_m) and dasr.get((_m, 1))) or pct(dasr[(_m, 1)]) <= pct(vasr[_m]):
        continue
    _keys = [k for k in _van_q if k[0] == _m and k in _def_q]
    _b = sum(1 for k in _keys if _van_q[k] == 1 and _def_q[k] == 0)
    _c = sum(1 for k in _keys if _van_q[k] == 0 and _def_q[k] == 1)
    _worse.append((_m, pct(dasr[(_m, 1)]) - pct(vasr[_m]), _b, _c, mcnemar_exact(_b, _c)))
_worse_txt = ''.join(
    f' For {DISP[_m]} attack success rises by {_d:.0f} points, which is not '
    f'significant (McNemar exact ${fmt_p(_p)}$, $b{{=}}{_b}$, $c{{=}}{_c}$).'
    if _p >= 0.05 else
    f' For {DISP[_m]} attack success rises by {_d:.0f} points '
    f'(McNemar exact ${fmt_p(_p)}$, $b{{=}}{_b}$, $c{{=}}{_c}$).'
    for _m, _d, _b, _c, _p in _worse)

if present and vasr:
    b = ['\\begin{table}[t]', '  \\centering',
         '  \\caption{The change in attack success rate the defense makes at '
         '$\\omega{=}1$, with both sides measured in the same units. Negative '
         'values are reductions, and the reduction grows with the model\'s '
         'undefended vulnerability.' + _worse_txt + '}',
         '  \\label{tab:benefit}', '  \\setlength{\\tabcolsep}{4pt}',
         '  \\begin{tabular}{lrrr}', '    \\toprule',
         '    model & undefended & defended ($\\omega{=}1$) & change \\\\',
         '    \\midrule']
    ranked = sorted([m for m in present if vasr.get(m)],
                    key=lambda m: -pct(vasr[m]))
    for m in ranked:
        u = pct(vasr[m])
        d = pct(dasr[(m, 1)]) if dasr.get((m, 1)) else float('nan')
        row = f'    {DISP[m]} & {u:.0f}\\% & {d:.0f}\\% & {d - u:+.0f}\\,pt \\\\'
        if d - u > 0:
            row = row.replace(f'{d - u:+.0f}\\,pt', f'\\textbf{{{d - u:+.0f}\\,pt}}')
        b.append(row)
    b += ['    \\bottomrule', '  \\end{tabular}', '\\end{table}']
    write('tab_benefit.tex', '\n'.join(b) + '\n', f'{VAN} and {OMEGA}',
          'both columns are ASR so they are directly comparable')

# ---------------------------------------------------------------- tab_surface
sw = rows(SWEEP)
if sw:
    cells = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in sw:
        if r['k_prime'] != '1':
            continue
        key = (float(r['alpha']), float(r['beta']), r['model'])
        cells[key][float(r['mu']) <= 1.0].append(int(r['attacker_kw_survived']))
    by_alpha = collections.defaultdict(lambda: ([], []))
    n_straddle = 0
    for (al, be, m), d in cells.items():
        v, n = d.get(True, []), d.get(False, [])
        if v and n:
            n_straddle += 1
        by_alpha[al][0].extend(v)
        by_alpha[al][1].extend(n)
    allv = [x for al in by_alpha for x in by_alpha[al][0]]
    alln = [x for al in by_alpha for x in by_alpha[al][1]]
    b = ['\\begin{table}[t]', '  \\centering',
         '  \\caption{Attacker keyword survival either side of the vacuity '
         'boundary, pooled over $\\beta$ and over three models ($k\'=1$). '
         'Configurations with $\\alpha{=}0.1$ are vacuous on every query and '
         'therefore provide no contrast; they are shown but excluded from the '
         'agreement count.}',
         '  \\label{tab:surface}', '  \\begin{tabular}{lrr}', '    \\toprule',
         '    & $\\mu \\le 1$ & $\\mu > 1$ \\\\', '    \\midrule']
    for al in sorted(by_alpha):
        v, n = by_alpha[al]
        lab = f'$\\alpha={al}$' + ('$^\\dagger$' if not n else '')
        fv = f'{pct(v):.0f}\\% ({len(v)})' if v else '--'
        fn = f'{pct(n):.0f}\\% ({len(n)})' if n else '--'
        b.append(f'    {lab} & {fv} & {fn} \\\\')
    b += ['    \\midrule',
          f'    pooled & \\textbf{{{pct(allv):.1f}\\%}} ({len(allv)}) & '
          f'\\textbf{{{pct(alln):.1f}\\%}} ({len(alln)}) \\\\',
          '    \\bottomrule', '  \\end{tabular}', '\\end{table}']
    write('tab_surface.tex', '\n'.join(b) + '\n', SWEEP,
          f'k_prime=1; {n_straddle} of {len(cells)} (alpha,beta,model) cells '
          f'straddle the boundary\n'
          'cell counts in parentheses are query-rows, not cells')

# ---------------------------------------------------------------- tab_fix
fx = rows(FIX)
if fx:
    d = collections.defaultdict(list)
    for r in fx:
        if r['k_prime'] != '1':
            continue
        d[(r['model'], int(r['group_size']), r['threshold_mode'])].append(
            int(r['attacker_kw_survived']))
    dc = collections.defaultdict(list)
    for r in fx:
        if r['k_prime'] != '0':
            continue
        c = str(r.get('defended_correct', '')).strip()
        if c != '':
            dc[(r['model'], int(r['group_size']), r['threshold_mode'])].append(int(c))
    ws = sorted({w for _, w, _ in d})
    modes = ['n', 'floor2', 'k']
    lbl = {'n': 'upstream $\\min(\\alpha n,\\beta)$',
           'floor2': '$\\max(2,\\min(\\alpha n,\\beta))$',
           'k': '$\\min(\\alpha k,\\beta)$'}
    ms = [m for m in ORDER if any((m, w, 'n') in d for w in ws)]
    b = ['\\begin{table*}[t]', '  \\centering',
         '  \\caption{The mitigation. Flooring $\\mu$ at two corroborating '
         'responses closes both routes. It leaves clean accuracy unchanged at '
         '$\\omega{=}1$ and costs some at $\\omega{=}4$; replacing the adaptive '
         'term with a constant costs considerably more.}',
         '  \\label{tab:fix}',
         '  \\begin{tabular}{ll' + 'rr' * len(ws) + '}', '    \\toprule',
         '    & & ' + ' & '.join('\\multicolumn{2}{c}{$\\omega{=}%d$}' % w for w in ws)
         + ' \\\\',
         '    model & threshold & ' + ' & '.join('surv. & clean' for _ in ws) + ' \\\\',
         '    \\midrule']
    for m in ms:
        for i, mo in enumerate(modes):
            cells = []
            for w in ws:
                s = d.get((m, w, mo)); c = dc.get((m, w, mo))
                cells.append(f'{pct(s):.0f}\\%' if s else '--')
                cells.append(f'{pct(c):.0f}\\%' if c else '--')
            name = DISP[m] if i == 0 else ''
            b.append(f'    {name} & {lbl[mo]} & ' + ' & '.join(cells) + ' \\\\')
        b.append('    \\addlinespace')
    b += ['    \\bottomrule', '  \\end{tabular}', '\\end{table*}']
    # Clean accuracy, floor against upstream, paired on (model, q_idx). Section
    # VIII quotes these, so the claim about what the floor costs in clean
    # accuracy comes from the data at each omega rather than from the pooled
    # table cells. At omega=4 the floor does cost accuracy; the prose must say so.
    _cq = {(r['model'], int(r['group_size']), r['threshold_mode'], r['q_idx']):
           int(r['defended_correct']) for r in fx
           if r['k_prime'] == '0' and str(r.get('defended_correct', '')).strip() != ''}
    _facts = []
    for w, word in ((1, 'one'), (4, 'four')):
        _keys = [(m, q) for (m, ww, mo, q) in _cq if ww == w and mo == 'n'
                 and (m, w, 'floor2', q) in _cq]
        _lost = sum(1 for m, q in _keys if _cq[(m, w, 'n', q)] and not _cq[(m, w, 'floor2', q)])
        _gain = sum(1 for m, q in _keys if _cq[(m, w, 'floor2', q)] and not _cq[(m, w, 'n', q)])
        _up = pct([_cq[(m, w, 'n', q)] for m, q in _keys])
        _fl = pct([_cq[(m, w, 'floor2', q)] for m, q in _keys])
        _facts += [f'\\newcommand{{\\fixcleanlost{word}}}{{{_lost}}}',
                   f'\\newcommand{{\\fixcleangain{word}}}{{{_gain}}}',
                   f'\\newcommand{{\\fixcleanp{word}}}{{{fmt_p(mcnemar_exact(_lost, _gain))}}}',
                   f'\\newcommand{{\\fixcleanup{word}}}{{{_up:.0f}}}',
                   f'\\newcommand{{\\fixcleanfl{word}}}{{{_fl:.0f}}}']
        print(f'  [fix] clean acc omega={w}: upstream {_up:.1f}% floor {_fl:.1f}% '
              f'lost {_lost} gained {_gain} {fmt_p(mcnemar_exact(_lost, _gain))}')
    write('tab_fix.tex', '\n'.join(_facts + b) + '\n', FIX,
          'surv.: k_prime=1 attacker_kw_survived; clean: k_prime=0 defended_correct\n'
          'fixclean*: clean accuracy upstream vs floor2, paired on (model,q_idx), '
          'exact McNemar')

# ---------------------------------------------------------------- fig_ladder
if present:
    MARKS = ['*', 'square*', 'triangle*', 'diamond*', 'pentagon*', 'o']
    b = ['\\begin{figure}[t]', '  \\centering', '  \\begin{tikzpicture}',
         '    \\begin{axis}[width=\\columnwidth, height=5.4cm,',
         '      xlabel={passage group size $\\omega$},',
         '      ylabel={attacker survival (\\%)},',
         '      xtick={1,2,3,4,5}, ymin=0, ymax=105,',
         '      legend style={font=\\scriptsize, at={(0.02,0.98)}, anchor=north west,'
         ' draw=none, fill opacity=0.8, text opacity=1},',
         '      legend cell align=left, grid=major, grid style={gray!20},',
         '      tick label style={font=\\footnotesize},'
         ' label style={font=\\footnotesize}]']
    # shade the vacuous region omega>=4
    b.append('      \\addplot[draw=none, fill=gray!12, forget plot] coordinates '
             '{(3.5,0) (5.5,0) (5.5,105) (3.5,105)} \\closedcycle;')
    b.append('      \\node[font=\\scriptsize, anchor=north east] at (axis cs:5.4,100) '
             '{$\\mu\\le1$};')
    for i, m in enumerate(present):
        pts = ' '.join(f'({w},{pct(surv[(m, w)]):.1f})' for w in OMEGAS)
        b.append(f'      \\addplot[mark={MARKS[i % len(MARKS)]}, mark size=1.6pt, '
                 f'thick] coordinates {{{pts}}};')
        b.append(f'      \\addlegendentry{{{DISP[m]}}}')
    b += ['    \\end{axis}', '  \\end{tikzpicture}',
          '  \\caption{Attacker keyword survival against passage group size. The '
          'shaded region is where $\\lceil k/\\omega\\rceil \\le 1/\\alpha$ holds and '
          'the filter is vacuous by Theorem~\\ref{thm:unconditional}. Five of six '
          'models collapse there; Llama-3.3-70B does not, for a reason the '
          'undefended control explains (Section~\\ref{sec:gate}).}',
          '  \\label{fig:ladder}', '\\end{figure}']
    write('fig_ladder.tex', '\n'.join(b) + '\n', OMEGA,
          'k_prime=1, attacker_kw_survived, by (model, group_size)')

# ---------------------------------------------------------------- fig_benefit
if present and vasr:
    b = ['\\begin{figure}[t]', '  \\centering', '  \\begin{tikzpicture}',
         '    \\begin{axis}[width=\\columnwidth, height=5.4cm,',
         '      xlabel={undefended attack success rate (\\%)},',
         '      ylabel={change in ASR from the defense (pt)},',
         '      xmin=0, xmax=100, grid=major, grid style={gray!20},',
         '      tick label style={font=\\footnotesize},'
         ' label style={font=\\footnotesize}]',
         '      \\addplot[draw=black!45, dashed, forget plot] coordinates '
         '{(0,0) (100,0)};']
    pts, labs = [], []
    for m in present:
        if not (vasr.get(m) and dasr.get((m, 1))):
            continue
        u, dd = pct(vasr[m]), pct(dasr[(m, 1)])
        pts.append((u, dd - u))
        labs.append(DISP[m])
    b.append('      \\addplot[only marks, mark=*, mark size=2pt] coordinates {'
             + ' '.join(f'({x:.1f},{y:.1f})' for x, y in pts) + '};')
    for (x, y), l in zip(pts, labs):
        anchor = 'west' if x < 70 else 'east'
        dx = 2 if x < 70 else -2
        b.append(f'      \\node[font=\\scriptsize, anchor={anchor}] at '
                 f'(axis cs:{x + dx:.1f},{y:.1f}) {{{l}}};')
    b += ['    \\end{axis}', '  \\end{tikzpicture}',
          '  \\caption{Undefended attack success rate against the change the '
          'defense makes at $\\omega{=}1$. Points below the dashed line are models '
          'the defense helps, and the more vulnerable the base model, the larger '
          'the reduction.' + _worse_txt + '}',
          '  \\label{fig:benefit}', '\\end{figure}']
    write('fig_benefit.tex', '\n'.join(b) + '\n', f'{VAN} and {OMEGA}',
          'x: vanilla undefended_asr; y: defended_asr(omega=1) - undefended_asr')

# ---------------------------------------------------------------- fig_tradeoff
# DELIBERATELY NOT GENERATED. The utility/security asymmetry it showed is
# already carried by tab_vanilla plus one sentence of text, and the paper is
# against a hard page limit. Cut rather than kept for decoration.

# ---------------------------------------------------------------- tab_lown
if om:
    lo_t = hi_t = lo_n = hi_n = 0
    body = []
    for m in ORDER:
        g = [r for r in om if r['model'] == m and int(r['group_size']) == 1
             and r['k_prime'] == '1']
        if not g:
            continue
        lo = [int(r['attacker_kw_survived']) for r in g if int(r['n_retained']) <= 3]
        hi = [int(r['attacker_kw_survived']) for r in g if int(r['n_retained']) >= 4]
        lo_t += sum(lo); lo_n += len(lo); hi_t += sum(hi); hi_n += len(hi)
        body.append(f'    {DISP[m]} & {pct(lo):.0f}\\% ($N{{=}}{len(lo)}$) & '
                    f'{pct(hi):.0f}\\% ($N{{=}}{len(hi)}$) \\\\')
    b = [r'\begin{table}[t]', r'  \centering',
         r'  \caption{Attacker keyword survival at $\omega{=}1$, the setting the '
         r'released code implements and where Route~2 is inactive, split on '
         r'whether the query fell into the vacuous regime $n \le 3$.}',
         r'  \label{tab:lown}', r'  \begin{tabular}{lrr}', r'    \toprule',
         r'    model & $n \le 3$ & $n \ge 4$ \\', r'    \midrule'] + body + [
         r'    \midrule',
         f'    pooled & \\textbf{{{100*lo_t/lo_n:.0f}\\%}} ($N{{=}}{lo_n}$) & '
         f'\\textbf{{{100*hi_t/hi_n:.0f}\\%}} ($N{{=}}{hi_n}$) \\\\',
         r'    \bottomrule', r'  \end{tabular}', r'\end{table}']
    write('tab_lown.tex', '\n'.join(b) + '\n', OMEGA,
          'group_size=1, k_prime=1, split on n_retained')

# ---------------------------------------------------------------- tab_coverage
# A CONFOUND THIS TABLE AVOIDS. Pooling RealtimeQA over all
# six models while Natural Questions and HotpotQA were Mistral-7B only (those
# two corpora were never run on the other five). Since n depends on the model's
# abstention behaviour, that compared a six-model average against two
# single-model measurements and made the corpus look like the only variable
